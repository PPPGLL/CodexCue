def system_ui_languages() -> list[str]:
    return QLocale.system().uiLanguages()


def ui_language() -> str:
    languages = system_ui_languages()
    first = languages[0] if languages else QLocale.system().name()
    return "zh" if first.lower().replace("_", "-").startswith("zh") else "en"


def tr(key: str, **values: object) -> str:
    return _STRINGS[ui_language()][key].format(**values)
